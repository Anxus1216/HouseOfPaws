import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { debugEnabledFromText } from './debug-config-value.mjs';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const configPath = join(root, 'config', 'debug.json');
const outputPath = join(root, 'js', 'debug-config.generated.js');
const release = process.argv.includes('--release');
let enabled = false;

if (!release) {
  try {
    const content = readFileSync(configPath, 'utf8');
    enabled = debugEnabledFromText(content);
    if (!enabled && content.trim() && !/"enable"\s*:\s*false/.test(content)) {
      console.warn('调试配置未包含布尔值 debug.enable=true，入口保持关闭。');
    }
  } catch (error) {
    if (error.code !== 'ENOENT') console.warn(`调试配置无效，已关闭调试入口：${error.message}`);
  }
}

writeFileSync(outputPath,
  `// Generated by scripts/prepare-debug-config.mjs. Run release:check before publishing.\n` +
  `export const DEBUG_ENABLED = ${enabled};\n`, 'utf8');
console.log(`调试入口：${enabled ? '开启' : '关闭'}${release ? '（发布模式）' : ''}`);
